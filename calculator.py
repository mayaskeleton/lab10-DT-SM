import math

def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

def divide(a, b):
    return b / a   # raise ZeroDivisionError if a == 0

def logarithm(a, b):
    return math.log(b,a)#loga(b)# use math library/raise ValueError

def exponent(a, b):
    return exponent(a,b)
